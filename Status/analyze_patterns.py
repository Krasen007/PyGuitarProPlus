#!/usr/bin/env python3
"""Analyze the binary patterns in detail."""

import sys
from pathlib import Path

ROOT = Path(r"F:\AI\repos\PyGuitarProPlus")
sys.path.insert(0, str(ROOT / "src"))

from guitarpro.gp6_container_metadata import (
    generate_part_configuration,
    generate_layout_configuration
)

def analyze_bytes(data: bytes, name: str):
    """Detailed byte analysis."""
    print(f"\n{name} ({len(data)} bytes):")
    print("=" * 70)
    
    # Hex dump
    for i in range(0, len(data), 16):
        chunk = data[i:i+16]
        hex_str = ' '.join(f'{b:02x}' for b in chunk)
        print(f"{i:04x}: {hex_str}")
    
    # Try to interpret as big-endian int32s
    print("\nAs big-endian int32 words:")
    for i in range(0, min(len(data), 32), 4):
        if i + 4 <= len(data):
            import struct
            val = struct.unpack('>I', data[i:i+4])[0]
            print(f"  [{i:2d}-{i+3:2d}]: 0x{val:08x} = {val}")

print("KNOWN GOOD (from real GP6 files):")
print("=" * 70)

print("\n1 Track:")
pc1 = bytes.fromhex('00 00 00 02 00 00 00 00 01 03 00 00 00 00 01 03 00 00 00 01'.replace(' ', ''))
lc1 = bytes.fromhex('00 00 00 04 00 00 ff ff 00 00 00 00'.replace(' ', ''))
analyze_bytes(pc1, "PartConfiguration")
analyze_bytes(lc1, "LayoutConfiguration")

