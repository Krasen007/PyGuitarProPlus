def test_preservation_efficiency():
    """Verify metadata isn't regenerated unnecessarily."""
    print("\n\nTest 3: Metadata preservation efficiency")
    print("=" * 70)
    
    # Load a 2-track file
    arr_path = ROOT / "Armin van Buuren - In And Out Of Love (ver 2) not full.gpx"
    song = gp.parse(arr_path)
    
    # Capture original
    original_meta = {}
    for name, content in song.format_extras.container_files:
        if name in ('misc.xml', 'PartConfiguration', 'LayoutConfiguration'):
            original_meta[name] = content
    
    print(f"Original metadata captured ({len(original_meta)} files)")
    
    # Make a non-structural change
    song.tracks[0].name = "Modified Name"
    
    # Write and reload
    with tempfile.NamedTemporaryFile(suffix='.gpx', delete=False) as tmp:
        tmp_path = Path(tmp.name)
    
    try:
        gp.write(song, tmp_path, version=(6, 0, 0))
        reloaded = gp.parse(tmp_path)
        
        # Check if metadata was preserved (not regenerated)
        preserved_count = 0
        for name, content in reloaded.format_extras.container_files:
            if name in original_meta:
                if content == original_meta[name]:
                    print(f"  ✅ {name}: PRESERVED (not regenerated)")
                    preserved_count += 1
                else:
                    print(f"  ⚠️  {name}: REGENERATED (unexpected)")
        
        if preserved_count == len(original_meta):
            print(f"\n✅ EFFICIENCY OPTIMIZATION WORKING: All {preserved_count} metadata files preserved")
            return True
        else:
            print(f"\n⚠️  EFFICIENCY ISSUE: Only {preserved_count}/{len(original_meta)} files preserved")
            return False
            
    finally:
        if tmp_path.exists():
            tmp_path.unlink()

