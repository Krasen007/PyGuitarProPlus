sys.path.insert(0, str(ROOT / "src"))
import guitarpro as gp

def hex_matches(actual: bytes, expected: bytes, name: str) -> bool:
    """Check if bytes match and report."""
    if actual == expected:
        print(f"  ✅ {name}: EXACT MATCH ({len(actual)} bytes)")
        return True
    else:
        print(f"  ❌ {name}: MISMATCH")
        print(f"     Expected: {expected.hex()}")
        print(f"     Got:      {actual.hex()}")
        return False

def test_1_track_binary_exact():
    """Verify 1-track binary metadata is byte-identical to Guitar Pro."""
    print("Test 1: 1-track metadata must be byte-identical to Guitar Pro")
    print("=" * 70)
    
    # Known good binary from Guitar Pro-generated file
    expected_part = bytes.fromhex('00 00 00 02 00 00 00 00 01 03 00 00 00 00 01 03 00 00 00 01'.replace(' ', ''))
    expected_layout = bytes.fromhex('00 00 00 04 00 00 ff ff 00 00 00 00'.replace(' ', ''))
    
    # Load 1-track file and re-save it
    vocal_path = ROOT / "Armin van Buuren - In And Out Of Love (ver 3 by Adrimor) full vocal only.gpx"
    song = gp.parse(vocal_path)
    
    # Remove a track and add it back to force regeneration
    track = song.tracks[0]
    song.tracks = []
    song.tracks.append(track)
    
    # Write and reload
    with tempfile.NamedTemporaryFile(suffix='.gpx', delete=False) as tmp:
        tmp_path = Path(tmp.name)
    
    try:
        gp.write(song, tmp_path, version=(6, 0, 0))
        reloaded = gp.parse(tmp_path)
        
        # Check binary metadata
        all_match = True
        for name, content in reloaded.format_extras.container_files:
            if name == 'PartConfiguration':
                all_match &= hex_matches(content, expected_part, "PartConfiguration")
            elif name == 'LayoutConfiguration':
                all_match &= hex_matches(content, expected_layout, "LayoutConfiguration")
        
        if all_match:
            print("\n✅ 1-TRACK PRODUCTION READY: Byte-identical to Guitar Pro")
            return True
        else:
            print("\n❌ 1-TRACK FAILED: Generated bytes don't match Guitar Pro")
            return False
            
    finally:
        if tmp_path.exists():
            tmp_path.unlink()

